/* 心境：0-100，影响突破与心魔判定（面板可见） */
function moodMod(){
  if(!S||S.mood===undefined)return 0;
  return clamp(Math.floor((S.mood-50)/12),-3,3);
}
function moodLabel(m){
  if(m>=85)return ['心境澄明','#8fd0a0'];
  if(m>=65)return ['心境安宁','#a9c99a'];
  if(m>=45)return ['心境平和','#c9c39a'];
  if(m>=25)return ['心境浮躁','#d9a08a'];
  return ['心境崩乱','#d96a6a'];
}
function addMood(n){
  if(!S)return;
  S.mood=clamp((S.mood===undefined?60:S.mood)+(n||0),0,100);
}
